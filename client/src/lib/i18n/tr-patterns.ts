/** Regular expressions for things like dates and short times ("Oct 17", "37m"). */
const MONTHS: Record<string, string> = {
  Jan: "Oca", Feb: "Şub", Mar: "Mar", Apr: "Nis", May: "May", Jun: "Haz", Jul: "Tem", Aug: "Ağu", Sep: "Eyl", Oct: "Eki", Nov: "Kas", Dec: "Ara",
};
export const TR_REGEX: [RegExp, (...m: string[]) => string][] = [
  [/^(\d+)m$/, (_, n) => `${n} dk`],
  [/^(\d+)h$/, (_, n) => `${n} sa`],
  [/^(\d+)d$/, (_, n) => `${n} g`],
  [/^(\d+)w$/, (_, n) => `${n} hf`],
  [/^· (\d+)([mhdw])$/, (_, n, u) => `· ${n} ${{ m: "dk", h: "sa", d: "g", w: "hf" }[u]}`],
  [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2})(, (\d{4}))?$/, (_, m, d, _y, y) => `${d} ${MONTHS[m]}${y ? ` ${y}` : ""}`],
  [/^Today (\d{1,2}:\d{2})$/, (_, t) => `Bugün ${t}`],
  [/^Yesterday (\d{1,2}:\d{2})$/, (_, t) => `Dün ${t}`],
  [/^Joined (.+)$/, (_, d) => `Katılma: ${d}`],
];
